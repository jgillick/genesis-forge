from __future__ import annotations

import copy
import math
from collections.abc import Generator, Mapping, Sequence
from contextlib import contextmanager
from typing import TYPE_CHECKING, Any

import genesis as gs
import numpy as np

from genesis_forge.terrain.map import TerrainMap
from genesis_forge.terrain.subterrains import Subterrain

if TYPE_CHECKING:
    from genesis.engine.entities import RigidEntity


GRID_SQUARE_SIZE = 0.5
"""The side of each square in the default grid texture, in meters."""
GRID_DARK = (25, 51, 76)
GRID_LIGHT = (51, 76, 102)
GRID_LINE = (255, 255, 255)
"""The default grid's colors."""
GRID_SQUARE_PIXELS = 32
"""The side of each square in the default grid texture, in pixels. The line is one pixel."""
GRID_TEXTURE_MAX_PIXELS = 4096
"""The largest side of the default grid texture, in pixels."""


class TerrainLayout:
    """
    A grid of subterrains, generated by Genesis Forge and added to the scene as one terrain.

    Compared to ``gs.morphs.Terrain``, every subterrain has its own params and its own random seed,
    and can have its own name. So two rough areas can have different heights, and the
    :class:`~genesis_forge.managers.TerrainManager` can tell them apart.

    A subterrain is named by its ``name``, or its ``type`` if it has no name. A name used by
    several subterrains is numbered in grid order (``rough_0``, ``rough_1``, ...), and the name
    itself selects any one of them. Every grid position still gets its own seed, so putting the
    same subterrain in several places makes several different patches of that kind of ground.

    Creating the layout checks it, generates the terrain, and adds it to the scene. The layout
    keeps its own copy of the subterrains, so changing one afterwards has no effect on it.

    Args:
        scene: The scene to add the terrain to.
        grid: The subterrains in a 2D list, as ``grid[x][y]``
              (the same layout as ``gs.morphs.Terrain(subterrain_types=...)``).
              A flat list is a single row, along the y axis.
        subterrain_size: The ``(x, y)`` size of each subterrain, in meters.
                         Must be a multiple of ``horizontal_scale``.
        horizontal_scale: The distance between two height field points, in meters.
        vertical_scale: The height resolution, in meters.
        pos: The position of the terrain's ``(x_min, y_min)`` corner.
        seed: The random seed. Each subterrain gets its own seed derived from it, so the terrain
              is the same on every run, and subterrains of the same type still differ.
              If None, the terrain is different every run.
        surface: The terrain surface, for example to give it a texture. Defaults to a blue
                 checkerboard of half-meter squares. Pass ``gs.surfaces.Default()`` for plain ground.
        **morph_kwargs: Other ``gs.morphs.Terrain`` options, like ``uv_scale`` or ``visualization``.

    Example::

        from genesis_forge import terrain

        rough = terrain.RandomUniform(name="rough", max_height=0.08)

        self.terrain_layout = terrain.TerrainLayout(
            self.scene,
            subterrain_size=(12, 12),
            grid=[
                [terrain.Flat(name="start"), rough],
                [rough, terrain.PyramidStairs(name="stairs")],
            ],
        )
    """

    def __init__(
        self,
        scene: gs.Scene,
        grid: Sequence[Sequence[Subterrain]],
        subterrain_size: tuple[float, float] = (12.0, 12.0),
        horizontal_scale: float = 0.25,
        vertical_scale: float = 0.005,
        pos: tuple[float, float, float] = (0.0, 0.0, 0.0),
        seed: int | None = 0,
        surface: gs.surfaces.Surface | None = None,
        **morph_kwargs: Any,
    ):
        """Check the layout, generate its height field, and add the terrain to the scene."""
        # Keep a copy, so changing a subterrain afterwards can't change the layout behind its back
        self._grid = copy.deepcopy(self._check_grid(grid))
        self._subterrain_size = self._check_size(subterrain_size, horizontal_scale)
        if vertical_scale <= 0:
            raise ValueError(f"vertical_scale must be positive, got {vertical_scale}.")
        if seed is not None and not isinstance(seed, int):
            raise TypeError(f"seed must be an int or None, got {type(seed).__name__}.")
        if len(pos) != 3:
            raise ValueError(f"pos must be an (x, y, z) position, got {pos!r}.")
        if "height_field" in morph_kwargs:
            raise TypeError(
                "height_field is generated by the TerrainLayout, and cannot be passed to it. "
                "Use terrain.HeightField for your own heights."
            )

        self._horizontal_scale = float(horizontal_scale)
        self._vertical_scale = float(vertical_scale)
        self._pos = tuple(float(v) for v in pos)
        self._seed = seed
        self._subterrains = tuple(
            subterrain for row in self._grid for subterrain in row
        )

        # Setup the map
        # A subterrain without a name goes by its type
        names = [[sub.name or sub.type for sub in row] for row in self._grid]
        types = [[sub.type for sub in row] for row in self._grid]
        self._map = TerrainMap.from_grid(
            self._pos, self._subterrain_size, labels=names, types=types
        )
        
        self._height_field = self._generate()
        self._entity: RigidEntity = self._add_to(scene, surface, morph_kwargs)

    """
    Properties
    """

    @property
    def subterrains(self) -> dict[str, Subterrain]:
        """The subterrains, by name, in grid order."""
        return dict(zip(self._map.names, self._subterrains, strict=True))

    @property
    def names(self) -> tuple[str, ...]:
        """The subterrain names in grid order -- ``grid[0][0], grid[0][1], ...`` -- which is also index order."""
        return self._map.names

    @property
    def groups(self) -> dict[str, tuple[str, ...]]:
        """The names shared by more than one subterrain, and the numbered names of each one."""
        # The map stores each group as subterrain indices; look up their numbered names
        groups = {}
        for shared_name, indices in self._map.groups.items():
            groups[shared_name] = tuple(self._map.names[i] for i in indices)
        return groups

    @property
    def map(self) -> TerrainMap:
        """The terrain's lookup table of subterrain names, types and areas."""
        return self._map

    @property
    def grid(self) -> tuple[tuple[Subterrain, ...], ...]:
        """The subterrains, as ``grid[x][y]``."""
        return self._grid

    @property
    def n_subterrains(self) -> tuple[int, int]:
        """The ``(x, y)`` number of subterrains in the grid."""
        return (len(self._grid), len(self._grid[0]))

    @property
    def subterrain_size(self) -> tuple[float, float]:
        """The ``(x, y)`` size of each subterrain, in meters."""
        return self._subterrain_size

    @property
    def size(self) -> tuple[float, float]:
        """The ``(x, y)`` size of the whole terrain, in meters."""
        n_x, n_y = self.n_subterrains
        return (n_x * self._subterrain_size[0], n_y * self._subterrain_size[1])

    @property
    def horizontal_scale(self) -> float:
        """The distance between two height field points, in meters."""
        return self._horizontal_scale

    @property
    def vertical_scale(self) -> float:
        """The height resolution, in meters."""
        return self._vertical_scale

    @property
    def pos(self) -> tuple[float, float, float]:
        """The position of the terrain's ``(x_min, y_min)`` corner."""
        return self._pos

    @property
    def entity(self) -> RigidEntity:
        """The terrain entity in the scene."""
        return self._entity

    @property
    def height_field(self) -> np.ndarray:
        """
        The whole terrain's height field, in vertical steps (multiply by ``vertical_scale`` for meters),
        as the ``height_field`` that ``gs.morphs.Terrain`` takes.
        """
        return self._height_field

    """
    Lookup
    """

    def grid_position(self, name: str) -> tuple[int, int]:
        """The ``(x, y)`` grid position of a subterrain."""
        return divmod(self._map.index(name), self.n_subterrains[1])

    def get_bounds(self, name: str | None = None) -> tuple[float, float, float, float]:
        """
        The bounds of a subterrain, or of the whole terrain.

        Returns:
            The bounds as ``(x_min, x_max, y_min, y_max)``.
        """
        return self._map.get_bounds(name)

    """
    Implementation
    """

    @staticmethod
    def _check_grid(
        grid: Sequence[Sequence[Subterrain]],
    ) -> tuple[tuple[Subterrain, ...], ...]:
        """
        Check that the grid is a rectangular 2D list of subterrain instances.

        A flat list of subterrains is taken as a single row. Other mistakes get an error with a
        hint at the fix: a list mixing rows and subterrains, rows of different lengths, a
        subterrain class instead of an instance, or a name that isn't a non-empty string.

        Returns:
            The grid as a tuple of row tuples.

        Raises:
            ValueError: If the grid is empty, not 2D, or not rectangular.
            TypeError: If a grid entry isn't a subterrain instance, or has an invalid name.
        """
        if isinstance(grid, (str, Mapping)) or not grid:
            raise ValueError(
                "grid must be a non-empty 2D list of subterrains, "
                "e.g. [[terrain.Flat(), terrain.RandomUniform()]]."
            )

        # If the first entry isn't a row, it's a flat list: one row of subterrains
        if not isinstance(grid[0], (list, tuple)):
            grid = [grid]

        rows = []
        for row in grid:
            if not isinstance(row, (list, tuple)):
                raise ValueError(
                    "grid must be a list of rows, each a list of subterrains, e.g. "
                    f"[[terrain.Flat()], [terrain.Wave()]]. Got a {type(row).__name__} "
                    "as a row: wrap it in a list."
                )
            rows.append(tuple(row))
        if not rows[0] or any(len(row) != len(rows[0]) for row in rows):
            raise ValueError(
                f"Every grid row must have the same, non-zero length. Got row lengths {[len(r) for r in rows]}."
            )

        for i, row in enumerate(rows):
            for j, subterrain in enumerate(row):
                if isinstance(subterrain, type) and issubclass(subterrain, Subterrain):
                    raise TypeError(
                        f"grid[{i}][{j}] is the class {subterrain.__name__}, not an instance. "
                        f"Did you mean {subterrain.__name__}()?"
                    )
                if not isinstance(subterrain, Subterrain):
                    raise TypeError(
                        f"grid[{i}][{j}] must be a Subterrain, like terrain.Flat(), "
                        f"got {type(subterrain).__name__}: {subterrain!r}"
                    )
                name = subterrain.name
                if name is not None and (not isinstance(name, str) or not name):
                    raise TypeError(
                        f"grid[{i}][{j}] has the name {name!r}; a name must be a non-empty string."
                    )
        return tuple(rows)

    @staticmethod
    def _check_size(
        subterrain_size: tuple[float, float], horizontal_scale: float
    ) -> tuple[float, float]:
        """
        Check that the subterrain size and horizontal scale fit together.

        The sizes and the scale must be positive, and each side of a subterrain must be a whole
        number of height field points apart, so every subterrain has the same shape and they line
        up edge to edge.

        Returns:
            The subterrain size, as floats.

        Raises:
            ValueError: If a size or the scale isn't positive, or a side isn't a multiple of
                the horizontal scale.
        """
        if horizontal_scale <= 0:
            raise ValueError(
                f"horizontal_scale must be positive, got {horizontal_scale}."
            )
        if len(subterrain_size) != 2 or any(size <= 0 for size in subterrain_size):
            raise ValueError(
                f"subterrain_size must be two positive sizes, got {subterrain_size!r}."
            )
        for size in subterrain_size:
            steps = size / horizontal_scale
            if not math.isclose(steps, round(steps), rel_tol=0, abs_tol=1e-6):
                raise ValueError(
                    f"subterrain_size {tuple(subterrain_size)} must be a multiple of "
                    f"horizontal_scale ({horizontal_scale})."
                )
        return (float(subterrain_size[0]), float(subterrain_size[1]))

    def _add_to(
        self,
        scene: gs.Scene,
        surface: gs.surfaces.Surface | None,
        morph_kwargs: dict[str, Any],
    ) -> RigidEntity:
        """Add the terrain to the scene, as a ``gs.morphs.Terrain`` built from the height field."""
        morph = gs.morphs.Terrain(
            height_field=self._height_field,
            horizontal_scale=self._horizontal_scale,
            vertical_scale=self._vertical_scale,
            pos=self._pos,
            **morph_kwargs,
        )
        if surface is None:
            surface = self._grid_surface()
        return scene.add_entity(morph=morph, surface=surface)

    def _grid_surface(self) -> gs.surfaces.Surface:
        """
        A blue checkerboard of half-meter squares with thin lines between them, stretched once
        over the whole terrain.
        """
        x_size, y_size = self.size
        squares_x = max(1, round(x_size / GRID_SQUARE_SIZE))
        squares_y = max(1, round(y_size / GRID_SQUARE_SIZE))
        # Fewer pixels per square on a large terrain, so the texture doesn't get oversized
        pixels = max(
            2,
            min(
                GRID_SQUARE_PIXELS, GRID_TEXTURE_MAX_PIXELS // max(squares_x, squares_y)
            ),
        )

        # The pixel coordinates, as a column of rows (y) and a row of columns (x)
        y = np.arange(squares_y * pixels)[:, None]
        x = np.arange(squares_x * pixels)[None, :]

        # A square is dark when its row and column add up to an even number, like a chessboard
        dark = (y // pixels + x // pixels) % 2 == 0
        # The first pixel row and column of every square draw the line between squares
        line = (y % pixels == 0) | (x % pixels == 0)

        image = np.empty((*dark.shape, 3), dtype=np.uint8)
        image[:] = GRID_LIGHT
        image[dark] = GRID_DARK
        image[line] = GRID_LINE
        return gs.surfaces.Default(
            diffuse_texture=gs.textures.ImageTexture(image_array=image)
        )

    def _subterrain_shape(self) -> tuple[int, int]:
        """The ``(x, y)`` number of height field points in one subterrain, edges included."""
        x_size, y_size = self._subterrain_size
        # A side split into N steps has N + 1 points, counting both edges
        x_points = round(x_size / self._horizontal_scale) + 1
        y_points = round(y_size / self._horizontal_scale) + 1
        return (x_points, y_points)

    def _generate(self) -> np.ndarray:
        """Generate every subterrain, and stitch them into one height field."""
        shape = self._subterrain_shape()
        x_points, y_points = shape
        x_steps, y_steps = x_points - 1, y_points - 1
        n_x, n_y = self.n_subterrains

        # Neighbors share their edge points, so the whole terrain has one more point than steps
        height_field = np.full((n_x * x_steps + 1, n_y * y_steps + 1), -np.inf)

        for index, (name, subterrain) in enumerate(
            zip(self._map.names, self._subterrains, strict=True)
        ):
            heights = self._generate_subterrain(index, name, subterrain, shape)

            # The part of the height field this subterrain covers
            grid_x, grid_y = divmod(index, n_y)
            x_start = grid_x * x_steps
            y_start = grid_y * y_steps
            area = height_field[
                x_start : x_start + x_points, y_start : y_start + y_points
            ]

            # Where it meets a neighbor, keep the higher of the two edges
            np.maximum(area, heights / self._vertical_scale, out=area)

        return height_field

    def _generate_subterrain(
        self, index: int, name: str, subterrain: Subterrain, shape: tuple[int, int]
    ) -> np.ndarray:
        """Generate one subterrain's heights, in meters, with its own seed, then ease and check them."""
        with self._seeded(index):
            heights = subterrain.generate(
                shape, self._horizontal_scale, self._vertical_scale
            )

        heights = np.asarray(heights, dtype=np.float64)
        description = f"Subterrain '{name}' ({type(subterrain).__name__})"
        if heights.shape != shape:
            raise ValueError(
                f"{description} generated a height field of shape {heights.shape}, "
                f"expected {shape}."
            )
        heights = subterrain.ease_edges(heights, self._horizontal_scale)
        if not np.all(np.isfinite(heights)):
            raise ValueError(f"{description} generated non-finite heights.")
        return heights

    @contextmanager
    def _seeded(self, index: int) -> Generator[None, None, None]:
        """
        Seed numpy's global random state for one subterrain, and restore the caller's state
        afterwards. Does nothing if the layout has no seed.

        The first subterrain is seeded the way ``gs.morphs.Terrain`` seeds its subterrains, so a
        one-subterrain layout matches it. Every other one gets its own seed sequence, which
        never overlaps another subterrain's or another seed's.
        """
        if self._seed is None:
            yield
            return

        saved_state = np.random.get_state()
        np.random.seed(self._seed if index == 0 else [self._seed, index])
        try:
            yield
        finally:
            np.random.set_state(saved_state)
